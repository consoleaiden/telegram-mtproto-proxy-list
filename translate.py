def localize(html: str) -> str:
    for pattern, repl in REGEX:
        html = re.sub(pattern, repl, html)

    for src in sorted(EXACT, key=len, reverse=True):
        html = html.replace(src, EXACT[src])

    def word_repl(match):
        word = match.group(0)
        for candidate in (word, word.lower().capitalize()):
            if candidate in WORD:
                return WORD[candidate]
        return word

    html = re.sub(r'[\u0400-\u04FF][\u0400-\u04FF-]*', word_repl, html)
    # tidy up: collapse spaces that appeared from dropped Russian prepositions and
    # join neighbouring CJK words (the generated labels read better without spaces)
    html = re.sub(r'[ \t]{2,}', ' ', html)
    for _ in range(3):
        html = re.sub(r'([\u4e00-\u9fff])[ \t]+([\u4e00-\u9fff])', r'\1\2', html)
    return html


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'index.html'
    dst = sys.argv[2] if len(sys.argv) > 2 else src
    html = io.open(src, encoding='utf-8').read()

    before = len(re.findall(r'[\u0400-\u04FF]', html))
    html = localize(html)
    leftover = re.findall(r'[\u0400-\u04FF][\u0400-\u04FF\s-]{0,40}', html)

    io.open(dst, 'w', encoding='utf-8', newline='\n').write(html)
    print('localized %s -> %s (cyrillic %d -> %d)' % (src, dst, before, len(leftover)))
    if leftover:
        # New upstream wording we have not mapped yet: still publish the fresh data,
        # but make it visible in the Actions log.
        print('WARNING: %d untranslated fragment(s): %s' % (len(leftover), leftover[:10]))


if __name__ == '__main__':
    main()
